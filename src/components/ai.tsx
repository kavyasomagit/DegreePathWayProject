"use client";

import { useEffect, useRef, useState } from "react";
import type { AiErrorCode } from "@/contract/types";
import { IconCheck, IconCopy, IconSparkle } from "./Icons";

export const AI_UNAVAILABLE = "AI is unavailable right now. Your plan will still be built from student data.";

/** Friendly, student-facing message for each AiError code. */
export function aiErrorMessage(code: AiErrorCode): string {
  switch (code) {
    case "not_configured":
    case "invalid_key":
    case "no_quota":
      return AI_UNAVAILABLE;
    case "rate_limited":
      return "The AI is busy right now. Wait a moment and try again.";
    case "timeout":
      return "The AI took too long to respond. Please try again.";
    default:
      return "Something went wrong with the AI. Please try again.";
  }
}

export const EMAIL_SUBJECT = "Advice from a Ridgeview student";

export function mailtoHref(email: string, body?: string): string {
  const params = [`subject=${encodeURIComponent(EMAIL_SUBJECT)}`];
  if (body) params.push(`body=${encodeURIComponent(body)}`);
  return `mailto:${email}?${params.join("&")}`;
}

/** Small badge marking AI-generated content. */
export function AiBadge({ className = "" }: { className?: string }) {
  return (
    <span
      className={`inline-flex items-center gap-1 rounded-full bg-fuchsia-100 px-2 py-0.5 text-xs font-semibold text-fuchsia-800 ring-1 ring-inset ring-fuchsia-200 ${className}`}
      title="Generated by AI"
    >
      <IconSparkle width={12} height={12} />
      AI
    </span>
  );
}

export function CopyButton({ text, className = "" }: { text: string; className?: string }) {
  const [copied, setCopied] = useState(false);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEffect(
    () => () => {
      if (timer.current) clearTimeout(timer.current);
    },
    [],
  );

  async function copy() {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      if (timer.current) clearTimeout(timer.current);
      timer.current = setTimeout(() => setCopied(false), 2000);
    } catch {
      // clipboard blocked (e.g. insecure context); the text is still visible to select manually
    }
  }

  return (
    <button
      type="button"
      onClick={copy}
      className={`inline-flex items-center justify-center gap-1.5 rounded-lg border border-slate-300 bg-white px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50 ${className}`}
    >
      {copied ? <IconCheck className="text-emerald-600" /> : <IconCopy />}
      <span aria-live="polite">{copied ? "Copied" : "Copy"}</span>
    </button>
  );
}
